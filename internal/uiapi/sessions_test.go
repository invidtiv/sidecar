func TestBrowserProofGuardsAndConcurrentSingleUse(t *testing.T) {
	h := newHarness(t)
	key, paired := h.pairBrowserKey()
	body, _ := json.Marshal(SessionProofChallengeRequest{RegistrationID: paired.RegistrationID})
	for _, path := range []string{"/api/v0/pairing/session-proof", "/api/v0/pairing/session-proof/verify"} {
		r, b := h.localDo(req{method: http.MethodPost, path: path, body: string(body)})
		expect(t, r, b, 403, CodeNotServedHere)
		r, b = h.tailnetDo(req{method: http.MethodPost, path: path, body: string(body), header: mutationHeaders("https://"+testTailnetHost, map[string]string{tailscaleLoginHead: testTailnetLogin})})
		expect(t, r, b, 403, CodeNotServedHere)
		pairedOrigin := "http://paired.example:5173"
		token := h.pairOrigin(pairedOrigin)
		r, b = h.browserDo(req{method: http.MethodPost, path: path, body: string(body), header: mutationHeaders(pairedOrigin, map[string]string{"Authorization": "Bearer " + token})})
		expect(t, r, b, 403, CodeOriginRefused)
		r, b = h.browserDo(req{method: http.MethodPost, path: path, body: string(body), header: map[string]string{"Origin": h.ownOrigin()}})
		expect(t, r, b, 403, CodeMutationRefused)
		r, b = h.browserDo(req{method: http.MethodPost, path: path, body: string(body), header: mutationHeaders("", nil)})
		expect(t, r, b, 403, CodeOriginRefused)
	}
	proof := signedProof(t, key, h.ownOrigin(), paired.RegistrationID, h.proofChallenge(paired.RegistrationID))
	var wg sync.WaitGroup
	statuses := make(chan int, 8)
	for i := 0; i < 8; i++ {
		wg.Add(1)
		go func() { defer wg.Done(); r, _ := h.submitProof(h.ownOrigin(), proof); statuses <- r.StatusCode }()
	}
	wg.Wait()
	close(statuses)
	success := 0
	for code := range statuses {
		if code == 200 {
			success++
		} else if code != 401 {
			t.Fatalf("concurrent proof status %d", code)
		}
	}
	if success != 1 {
		t.Fatalf("nonce redeemed %d times", success)
	}
	// A proof signed before revocation is refused even when its signature is valid.
	proof = signedProof(t, key, h.ownOrigin(), paired.RegistrationID, h.proofChallenge(paired.RegistrationID))
	h.revokeSessions("")
	r, b := h.submitProof(h.ownOrigin(), proof)
	expect(t, r, b, 401, CodeSessionProofInvalid)
}

func TestBrowserBearerExpiryRecheckedAtTicketAdmission(t *testing.T) {
	h := newHarness(t)
	_, paired := h.pairBrowserKey()
	h.clock.Advance(browserBearerTTL - 10*time.Second)
	r, b := h.browserDo(req{method: http.MethodPost, path: "/api/v0/ws-tickets", body: "{}", header: mutationHeaders(h.ownOrigin(), map[string]string{"Authorization": "Bearer " + paired.Token})})
	expect(t, r, b, 200, "")
	var issued TicketResponse
	if err := json.Unmarshal(b, &issued); err != nil {
		t.Fatal(err)
	}
	ticket := issued.Ticket
	client := sessionClient(paired.RegistrationID)
	stale := caller{listener: ListenerBrowser, auth: "session", origin: h.ownOrigin(), client: client, credential: hashToken(paired.Token)}
	if !h.s.callerLive(stale) {
		t.Fatal("unexpired browser bearer refused")
	}
	h.clock.Advance(10 * time.Second)
	if h.s.callerLive(stale) {
		t.Fatal("expired bearer authorization remained live")
	}
	h.expectBrowserClose(t, "ticket from expired bearer", "?ticket="+ticket, http.Header{"Origin": {h.ownOrigin()}}, CloseUnauthenticated)
}

// sessionClientLive reports whether client, a key from sessionClient, still
// names a session. Keys of other kinds are not sessions and always are.
func (a *authStore) sessionClientLive(client string) bool {
	if !strings.HasPrefix(client, "session:") {
		return true
	}
	a.mu.Lock()
	defer a.mu.Unlock()
	if err := a.reloadSessionsLocked(); err != nil {
		return false
	}
	s, ok := a.sessions[strings.TrimPrefix(client, "session:")]
	return ok && a.now().Before(s.ExpiresAt)
}

